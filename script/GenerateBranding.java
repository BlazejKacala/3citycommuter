import java.awt.BasicStroke;
import java.awt.Color;
import java.awt.Font;
import java.awt.Graphics2D;
import java.awt.RenderingHints;
import java.awt.Shape;
import java.awt.font.FontRenderContext;
import java.awt.geom.AffineTransform;
import java.awt.geom.Area;
import java.awt.geom.Ellipse2D;
import java.awt.geom.Path2D;
import java.awt.geom.PathIterator;
import java.awt.geom.RoundRectangle2D;
import java.awt.image.BufferedImage;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Locale;
import javax.imageio.ImageIO;

/** Run from the repository root: java script/GenerateBranding.java <bold-font.ttf>. */
class GenerateBranding {
    private static final Path RES = Path.of("composeApp/android/src/main/res");
    private static final Path BRAND = Path.of("design/branding");
    private static final String BLUE = "#1976D2";
    private static final String YELLOW = "#FFC107";
    private static final String WHITE = "#FFFFFF";
    private static final String NIGHT_BLUE = "#42A5F5";
    private static final double[][] STOPS = {{28, 20}, {66, 50}, {28, 80}};

    record Layer(Shape shape, String color) {}

    private static Ellipse2D circle(double x, double y, double r) {
        return new Ellipse2D.Double(x - r, y - r, r * 2, r * 2);
    }

    private static Area route() {
        Path2D path = new Path2D.Double();
        path.moveTo(28, 20);
        path.lineTo(59, 20);
        path.curveTo(86, 20, 86, 50, 60, 50);
        path.lineTo(44, 50);
        path.moveTo(60, 50);
        path.curveTo(88, 50, 88, 80, 60, 80);
        path.lineTo(28, 80);
        Area outline = new Area(new BasicStroke(13.5f, BasicStroke.CAP_ROUND,
                BasicStroke.JOIN_ROUND).createStrokedShape(path));
        for (double[] stop : STOPS) outline.add(new Area(circle(stop[0], stop[1], 11.5)));
        return outline;
    }

    private static List<Layer> logo(String color) {
        var layers = new java.util.ArrayList<Layer>();
        layers.add(new Layer(route(), color));
        for (double[] stop : STOPS) {
            layers.add(new Layer(circle(stop[0], stop[1], 7.4), WHITE));
            layers.add(new Layer(circle(stop[0], stop[1], 5), YELLOW));
        }
        return layers;
    }

    private static List<Layer> monochrome() {
        Area shape = route();
        for (double[] stop : STOPS) shape.subtract(new Area(circle(stop[0], stop[1], 5)));
        return List.of(new Layer(shape, WHITE));
    }

    // Centre the optical bounds, then leave room for adaptive-icon and splash masks.
    private static List<Layer> fit(List<Layer> layers, double canvas, double scale) {
        AffineTransform transform = new AffineTransform();
        transform.translate(canvas / 2 - 51 * scale, canvas / 2 - 50 * scale);
        transform.scale(scale, scale);
        return layers.stream().map(l -> new Layer(transform.createTransformedShape(l.shape), l.color)).toList();
    }

    private static String number(double value) {
        return String.format(Locale.ROOT, "%.3f", value).replaceAll("\\.?0+$", "");
    }

    private static String pathData(Shape shape) {
        StringBuilder result = new StringBuilder();
        double[] values = new double[6];
        for (PathIterator it = shape.getPathIterator(null); !it.isDone(); it.next()) {
            int type = it.currentSegment(values);
            result.append("MLQCZ".charAt(type));
            int count = switch (type) { case 0, 1 -> 2; case 2 -> 4; case 3 -> 6; default -> 0; };
            for (int i = 0; i < count; i++) result.append(i == 0 ? "" : ",").append(number(values[i]));
        }
        return result.toString();
    }

    private static void write(Path file, String content) throws Exception {
        Files.createDirectories(file.getParent());
        Files.writeString(file, content);
    }

    private static void vector(String name, int dp, int viewport, List<Layer> layers) throws Exception {
        vector(name, dp, dp, viewport, viewport, layers);
    }

    private static void vector(String name, int width, int height, int vw, int vh, List<Layer> layers) throws Exception {
        StringBuilder xml = new StringBuilder("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n");
        xml.append("<!-- Generated by script/GenerateBranding.java. -->\n");
        xml.append("<vector xmlns:android=\"http://schemas.android.com/apk/res/android\"\n");
        if (width > 200) {
            // The system splash API specifically requires a 288 dp icon canvas.
            xml.append("    xmlns:tools=\"http://schemas.android.com/tools\" tools:ignore=\"VectorRaster\"\n");
        }
        xml.append("    android:width=\"").append(width).append("dp\" android:height=\"").append(height).append("dp\"\n");
        xml.append("    android:viewportWidth=\"").append(vw).append("\" android:viewportHeight=\"").append(vh).append("\">\n");
        for (Layer layer : layers) xml.append("    <path android:fillColor=\"").append(layer.color)
                .append("\" android:pathData=\"").append(pathData(layer.shape)).append("\" />\n");
        xml.append("</vector>\n");
        write(RES.resolve("drawable/" + name + ".xml"), xml.toString());
    }

    private static void svg(String name, int size, List<Layer> layers) throws Exception {
        StringBuilder svg = new StringBuilder("<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 " + size + " " + size + "\">\n");
        svg.append("  <title>Przystanek Trójmiasto — Trzy przystanki</title>\n");
        for (Layer layer : layers) svg.append("  <path fill=\"").append(layer.color)
                .append("\" d=\"").append(pathData(layer.shape)).append("\"/>\n");
        svg.append("</svg>\n");
        write(BRAND.resolve(name + ".svg"), svg.toString());
    }

    private static void paint(Graphics2D g, List<Layer> layers) {
        for (Layer layer : layers) {
            g.setColor(Color.decode(layer.color));
            g.fill(layer.shape);
        }
    }

    private static BufferedImage raster(int size, int viewport, List<Layer> layers) {
        int supersampling = 4;
        BufferedImage large = new BufferedImage(size * supersampling, size * supersampling, BufferedImage.TYPE_INT_ARGB);
        Graphics2D g = large.createGraphics();
        g.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);
        g.scale((double) size * supersampling / viewport, (double) size * supersampling / viewport);
        paint(g, layers);
        g.dispose();
        BufferedImage image = new BufferedImage(size, size, BufferedImage.TYPE_INT_ARGB);
        g = image.createGraphics();
        g.setRenderingHint(RenderingHints.KEY_INTERPOLATION, RenderingHints.VALUE_INTERPOLATION_BICUBIC);
        g.drawImage(large, 0, 0, size, size, null);
        g.dispose();
        return image;
    }

    private static void png(Path file, BufferedImage image) throws Exception {
        Files.createDirectories(file.getParent());
        ImageIO.write(image, "png", file.toFile());
    }

    private static List<Layer> wordmark(Font font, String color) {
        var layers = new java.util.ArrayList<Layer>();
        FontRenderContext context = new FontRenderContext(null, true, true);
        String[] words = {"Przystanek", "Trójmiasto"};
        for (int i = 0; i < words.length; i++) {
            var glyphs = font.createGlyphVector(context, words[i]);
            var bounds = glyphs.getOutline().getBounds2D();
            AffineTransform position = AffineTransform.getTranslateInstance(100 - bounds.getCenterX(), 33 + 29 * i);
            for (int glyph = 0; glyph < glyphs.getNumGlyphs(); glyph++) {
                layers.add(new Layer(position.createTransformedShape(glyphs.getGlyphOutline(glyph)), color));
            }
        }
        return layers;
    }

    public static void main(String[] args) throws Exception {
        if (args.length != 1) throw new IllegalArgumentException("Pass a bold TTF font for the outlined wordmark.");
        Font font = Font.createFont(Font.TRUETYPE_FONT, Path.of(args[0]).toFile()).deriveFont(26f);
        List<Layer> foreground = fit(logo(WHITE), 108, .64);
        List<Layer> mono = fit(monochrome(), 108, .64);
        var launcher = new java.util.ArrayList<Layer>();
        launcher.add(new Layer(new RoundRectangle2D.Double(0, 0, 108, 108, 25, 25), BLUE));
        // Legacy and desktop icons have no outer adaptive layer that the OS crops away.
        launcher.addAll(fit(logo(WHITE), 108, .92));
        vector("ic_launcher_foreground", 108, 108, foreground);
        vector("ic_launcher_monochrome", 108, 108, mono);
        var splash = fit(logo("@color/splash_logo"), 100, .62);
        vector("ic_splash", 288, 100, splash);
        vector("splash_branding", 200, 80, 200, 80, wordmark(font, "@color/splash_wordmark"));
        svg("logo", 100, logo(BLUE));
        svg("logo-dark", 100, logo(NIGHT_BLUE));
        svg("launcher", 108, launcher);
        String[] densities = {"mdpi", "hdpi", "xhdpi", "xxhdpi", "xxxhdpi"};
        double[] factors = {1, 1.5, 2, 3, 4};
        for (int i = 0; i < densities.length; i++) {
            Path dir = RES.resolve("mipmap-" + densities[i]);
            png(dir.resolve("ic_launcher.png"), raster((int) (48 * factors[i]), 108, launcher));
        }
        png(Path.of("composeApp/desktop/src/main/resources/icon.png"), raster(256, 108, launcher));
        System.out.println("Generated Android vectors, density icons, desktop icon and SVG sources.");
    }
}
